function hexToString(hex) {
    if (!hex || typeof hex !== 'string') {
        return "";
    }
    let str = '';
    const cleanHex = hex.replace(/\s/g, '');
    if (cleanHex.length % 2 !== 0) {
        console.error("Invalid hex string for guild mark:", cleanHex);
        return "";
    }
    try {
        for (let i = 0; i < cleanHex.length; i += 2) {
            const hexByte = cleanHex.substr(i, 2);
            str += String.fromCharCode(parseInt(hexByte, 16));
        }
    } catch (e) {
        console.error("Error decoding hex string for guild mark:", e);
        return "";
    }
    return str;
}


function drawDvteamGuildMark(hex, size) {
    size = size || 32;
    const pixelSize = size / 8;
    const canvas = document.createElement('canvas');
    canvas.width = size;
    canvas.height = size;
    const ctx = canvas.getContext('2d');
    
    // Adaugă un fundal negru pentru a se potrivi cu aspectul din joc
    ctx.fillStyle = '#000000';
    ctx.fillRect(0, 0, size, size);
    
    const colors = { "0": null, "00": "0c0000", "17": "0c0000", "34": "818081", "51": "ffffff", "68": "ff0000", "65": "ff0000", "20": "ff0000", "85": "ff8000", "102": "ffff00", "119": "81ff00", "136": "00ff00", "221": "8100ff", "238": "ff00ff", "255": "ff0081", "153": "00ff81", "170": "00ffff", "236": "00ff81", "204": "0000ff", "94": "ff8000" };

    const codes = hex.trim().split(/\s+/).filter(c => c);

    // An 8x8 mark has 64 codes. Some servers might use 8x4 marks with 32 codes.
    // We adjust the grid width and center the 8x4 mark if needed.
    const gridWidth = (codes.length <= 32) ? 4 : 8;
    const xOffset = (gridWidth === 4) ? (2 * pixelSize) : 0;
    
    codes.forEach((code, index) => {
        const colorHex = colors[code.trim()];
        if (colorHex) {
            const x = (index % gridWidth) * pixelSize + xOffset;
            const y = Math.floor(index / gridWidth) * pixelSize;
            ctx.fillStyle = `#${colorHex}`;
            ctx.fillRect(x, y, pixelSize, pixelSize);
        }
    });

    return canvas.toDataURL('image/png');
}

function drawGuildMark(binaryData, size, serverFiles) {
    // MODIFIED: Handle DVTEAM's hex-encoded guild mark data
    if (serverFiles === 'DVTEAM') {
        const decodedMark = hexToString(binaryData);
        const codes = decodedMark.trim().split(/\s+/).filter(c => c);

        // Check for duplicated 8x4 mark data inside an 8x8 grid (64 codes total)
        if (codes.length === 64) {
            const firstHalf = codes.slice(0, 32);
            const secondHalf = codes.slice(32);
            // If the two halves are identical, we only want to draw the first one.
            if (JSON.stringify(firstHalf) === JSON.stringify(secondHalf)) {
                return drawDvteamGuildMark(firstHalf.join(' '), size);
            }
        }
        
        // Otherwise, draw the mark with the data as is.
        return drawDvteamGuildMark(decodedMark, size);
    }

    size = size || 40;
    const pixelSize = size / 8;
    const canvas = document.createElement('canvas');
    canvas.width = size;
    canvas.height = size;
    const ctx = canvas.getContext('2d');
    
    const colors = { "0": "#111111", "1": "#000000", "2": "#808080", "3": "#ffffff", "4": "#fe0000", "5": "#ff7f00", "6": "#ffff00", "7": "#80ff00", "8": "#00ff01", "9": "#00fe81", "A": "#00ffff", "B": "#0080ff", "C": "#0000fe", "D": "#7f00ff", "E": "#ff00fe", "F": "#ff0080" };

    for (let y = 0; y < 8; y++) {
        for (let x = 0; x < 8; x++) {
            const offset = y * 8 + x;
            const bit = binaryData.substr(offset, 1).toUpperCase();
            const color = colors[bit] || "#000000";
            ctx.fillStyle = color;
            ctx.fillRect(x * pixelSize, y * pixelSize, pixelSize, pixelSize);
        }
    }

    return canvas.toDataURL('image/png');
}

